//! Email notification module
//!
//! Sends alerts via email using SMTP.
//! Only sends to YOUR configured email address. NO TELEMETRY.

use tracing::debug;

use crate::config::EmailConfig;
use crate::monitor::{SecurityEvent, EventSeverity};

/// Email notification sender
#[cfg(feature = "email")]
pub struct EmailNotifier {
    config: EmailConfig,
}

#[cfg(not(feature = "email"))]
pub struct EmailNotifier {
    _private: (),
}

#[cfg(feature = "email")]
impl EmailNotifier {
    /// Create a new email notifier
    pub fn new(config: EmailConfig) -> Self {
        Self { config }
    }

    /// Send a security event via email
    pub async fn send(&self, event: &SecurityEvent) -> Result<(), EmailError> {
        use lettre::{
            Message, SmtpTransport, Transport,
            message::{header::ContentType, Mailbox},
            transport::smtp::authentication::Credentials,
        };

        let subject = format!(
            "[RansomWatch {}] {}",
            event.severity,
            event.event_type.description()
        );

        let body = self.format_email_body(event);

        debug!("Sending email alert to: {}", self.config.to);

        let from: Mailbox = self.config.from.parse()
            .map_err(|e| EmailError::InvalidAddress(format!("from: {}", e)))?;

        let to: Mailbox = self.config.to.parse()
            .map_err(|e| EmailError::InvalidAddress(format!("to: {}", e)))?;

        let email = Message::builder()
            .from(from)
            .to(to)
            .subject(subject)
            .header(ContentType::TEXT_PLAIN)
            .body(body)
            .map_err(|e| EmailError::BuildFailed(e.to_string()))?;

        let creds = Credentials::new(
            self.config.username.clone(),
            self.config.password.clone(),
        );

        let mailer = if self.config.use_tls {
            SmtpTransport::starttls_relay(&self.config.smtp_server)
                .map_err(|e| EmailError::ConnectionFailed(e.to_string()))?
                .credentials(creds)
                .port(self.config.smtp_port)
                .build()
        } else {
            SmtpTransport::builder_dangerous(&self.config.smtp_server)
                .credentials(creds)
                .port(self.config.smtp_port)
                .build()
        };

        mailer.send(&email)
            .map_err(|e| EmailError::SendFailed(e.to_string()))?;

        debug!("Email sent successfully");
        Ok(())
    }

    /// Format the email body
    fn format_email_body(&self, event: &SecurityEvent) -> String {
        let severity_banner = match event.severity {
            EventSeverity::Info => "ℹ️  INFORMATIONAL",
            EventSeverity::Warning => "⚠️  WARNING",
            EventSeverity::Critical => "🚨 CRITICAL ALERT",
        };

        format!(r#"
================================================================================
                         RANSOMWATCH SECURITY ALERT
================================================================================

{}

Event: {}
Severity: {}
Time: {}
Path: {}

--------------------------------------------------------------------------------
DETAILS
--------------------------------------------------------------------------------

{}

--------------------------------------------------------------------------------
RECOMMENDATION
--------------------------------------------------------------------------------

{}

--------------------------------------------------------------------------------
EVENT INFORMATION
--------------------------------------------------------------------------------

Event ID: {}
Detection Method: File System Monitor

================================================================================
This alert was generated by RansomWatch - Local Ransomware Monitor
No data was sent to any external service. This email was sent only to you.
================================================================================
"#,
            severity_banner,
            event.event_type.description(),
            event.severity,
            event.timestamp.format("%Y-%m-%d %H:%M:%S UTC"),
            event.path.display(),
            event.context.as_deref().unwrap_or("No additional details"),
            event.recommendation,
            event.id
        )
    }

    /// Test the email configuration
    pub async fn test(&self) -> Result<(), EmailError> {
        use lettre::{
            Message, SmtpTransport, Transport,
            message::{header::ContentType, Mailbox},
            transport::smtp::authentication::Credentials,
        };

        let from: Mailbox = self.config.from.parse()
            .map_err(|e| EmailError::InvalidAddress(format!("from: {}", e)))?;

        let to: Mailbox = self.config.to.parse()
            .map_err(|e| EmailError::InvalidAddress(format!("to: {}", e)))?;

        let email = Message::builder()
            .from(from)
            .to(to)
            .subject("[RansomWatch] Test Notification")
            .header(ContentType::TEXT_PLAIN)
            .body("This is a test email from RansomWatch.\n\nIf you received this, email alerts are working correctly.".to_string())
            .map_err(|e| EmailError::BuildFailed(e.to_string()))?;

        let creds = Credentials::new(
            self.config.username.clone(),
            self.config.password.clone(),
        );

        let mailer = if self.config.use_tls {
            SmtpTransport::starttls_relay(&self.config.smtp_server)
                .map_err(|e| EmailError::ConnectionFailed(e.to_string()))?
                .credentials(creds)
                .port(self.config.smtp_port)
                .build()
        } else {
            SmtpTransport::builder_dangerous(&self.config.smtp_server)
                .credentials(creds)
                .port(self.config.smtp_port)
                .build()
        };

        mailer.send(&email)
            .map_err(|e| EmailError::SendFailed(e.to_string()))?;

        Ok(())
    }
}

#[cfg(not(feature = "email"))]
impl EmailNotifier {
    pub fn new(_config: EmailConfig) -> Self {
        Self { _private: () }
    }

    pub async fn send(&self, _event: &SecurityEvent) -> Result<(), EmailError> {
        Err(EmailError::NotEnabled)
    }

    pub async fn test(&self) -> Result<(), EmailError> {
        Err(EmailError::NotEnabled)
    }
}

#[derive(Debug)]
pub enum EmailError {
    InvalidAddress(String),
    BuildFailed(String),
    ConnectionFailed(String),
    SendFailed(String),
    NotEnabled,
}

impl std::fmt::Display for EmailError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            EmailError::InvalidAddress(e) => write!(f, "Invalid address: {}", e),
            EmailError::BuildFailed(e) => write!(f, "Failed to build email: {}", e),
            EmailError::ConnectionFailed(e) => write!(f, "SMTP connection failed: {}", e),
            EmailError::SendFailed(e) => write!(f, "Failed to send email: {}", e),
            EmailError::NotEnabled => write!(f, "Email feature not enabled"),
        }
    }
}

impl std::error::Error for EmailError {}
